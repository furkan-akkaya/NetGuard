"""Bring transferred lab captures into the repository and write the manifest.

    python3 eval/lab/ingest.py TRANSFER_DIR

TRANSFER_DIR holds what the VMs produced: NAME.pcap, NAME.sha256 and
NAME.meta.txt from the Ubuntu victim, and NAME.attack.txt from Kali (attack
experiments). For every experiment in eval/lab/experiments.toml whose capture
is present, this script

* verifies the capture against the SHA-256 computed on the victim,
* copies it into captures/ (git-ignored), refusing to overwrite a different file,
* writes eval/captures.toml (git-ignored): the labels from experiments.toml
  plus the hash, tool, tool version and command recorded during the run.

It never executes a recorded command. Then run:

    uv run netguard lab evaluate --manifest eval/captures.toml
"""

from __future__ import annotations

import hashlib
import json
import re
import shutil
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
EXPERIMENTS = ROOT / "eval" / "lab" / "experiments.toml"
CAPTURES = ROOT / "captures"
MANIFEST = ROOT / "eval" / "captures.toml"
NAME = re.compile(r"^[a-z0-9][a-z0-9-]{0,62}$")


class IngestError(Exception):
    pass


def _fields(path: Path) -> dict[str, str]:
    """'key: value' lines written by the lab scripts."""
    out: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        key, sep, value = line.partition(": ")
        if sep:
            out[key.strip()] = value.strip()
    return out


def _sha256(path: Path) -> str:
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def _q(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)  # a JSON string is a valid TOML basic string


def ingest(transfer: Path) -> list[str]:
    experiments = tomllib.loads(EXPERIMENTS.read_text(encoding="utf-8"))["experiments"]
    entries: list[str] = []
    done: list[str] = []
    for exp in experiments:
        name = exp["name"]
        if not NAME.match(name):
            raise IngestError(f"invalid experiment name: {name!r}")
        pcap = transfer / f"{name}.pcap"
        if not pcap.exists():
            continue
        recorded = (transfer / f"{name}.sha256").read_text().split()[0].lower()
        actual = _sha256(pcap)
        if actual != recorded:
            raise IngestError(f"{name}: SHA-256 differs from the one computed on the victim; transfer again")
        meta = _fields(transfer / f"{name}.meta.txt")
        dropped = meta.get("kernel_dropped")
        if dropped is None:
            print(f"warning: {name}: no kernel-drop count in {name}.meta.txt", file=sys.stderr)
        elif dropped != "0":
            print(f"warning: {name}: tcpdump reported {dropped} packets dropped by the kernel", file=sys.stderr)
        if meta.get("captured") != meta.get("received_by_filter"):
            print(
                f"warning: {name}: tcpdump received {meta.get('received_by_filter')} packets "
                f"but wrote {meta.get('captured')}; the capture is incomplete",
                file=sys.stderr,
            )
        if exp["kind"] == "attack":
            attack = _fields(transfer / f"{name}.attack.txt")
            tool, version, command = attack["tool"], attack["tool_version"], attack["command"]
        else:
            tool, version, command = "tcpdump", meta.get("tcpdump", "unknown"), exp["script"]
        target = CAPTURES / f"{name}.pcap"
        CAPTURES.mkdir(exist_ok=True)
        if target.exists() and _sha256(target) != actual:
            raise IngestError(f"{target} exists with different contents; refusing to overwrite")
        shutil.copyfile(pcap, target)
        note = "; ".join(
            [exp["note"], meta.get("interface", "?"), meta.get("start_utc", "?"), f"kernel_dropped={dropped}"]
        )
        labels = ", ".join(
            "{ detector = " + _q(e["detector"]) + ", entity = " + _q(e["entity"]) + " }" for e in exp["expected"]
        )
        entries.append(
            "\n".join(
                [
                    "[[captures]]",
                    f"name = {_q(name)}",
                    f"path = {_q('../captures/' + name + '.pcap')}",
                    f"sha256 = {_q(actual)}",
                    f"kind = {_q(exp['kind'])}",
                    'provenance = "lab"',
                    f"tool = {_q(tool)}",
                    f"tool_version = {_q(version)}",
                    f"command = {_q(command)}",
                    f"note = {_q(note)}",
                    f"expected = [{labels}]",
                ]
            )
        )
        done.append(name)
    if not entries:
        raise IngestError(f"no capture of a known experiment in {transfer}")
    MANIFEST.write_text(
        "# Generated by eval/lab/ingest.py from eval/lab/experiments.toml; do not edit labels here.\n"
        "schema_version = 1\n\n" + "\n\n".join(entries) + "\n",
        encoding="utf-8",
    )
    return done


def main(argv: list[str]) -> int:
    if len(argv) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    try:
        done = ingest(Path(argv[0]))
    except (IngestError, OSError, KeyError) as exc:
        print(f"ingest failed: {exc}", file=sys.stderr)
        return 1
    print(f"ingested {', '.join(done)}; wrote {MANIFEST.relative_to(ROOT)}")
    print("next: uv run netguard lab evaluate --manifest eval/captures.toml")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
